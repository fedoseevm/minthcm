namespace MintHCM\Api\Controllers;

use Slim\Psr7\Response;
use Psr\Http\Message\ServerRequestInterface as Request;

class AnonymousDataController
{
    public function sendAnonData(Request $request, Response $response, array $args): Response
    {
        $userIP = $_SERVER['HTTP_X_FORWARDED_FOR'] ?? $_SERVER["REMOTE_ADDR"];
        $anonData =  json_encode([
            "ip" => $userIP
        ]);

        $url = "https://fedoseevm80-57.int2.evolpe.net/minthcm-statistic-data-store/index.php";
        $ch = curl_init($url);

        curl_setopt($ch, CURLOPT_RETURNTRANSFER, true);
        curl_setopt($ch, CURLOPT_POST, true);
        curl_setopt($ch, CURLOPT_HTTPHEADER, [
            "Content-Type: application/json"
        ]);
        curl_setopt($ch, CURLOPT_POSTFIELDS, $anonData);
        curl_setopt($ch, CURLOPT_SSL_VERIFYPEER, true);
        curl_setopt($ch, CURLOPT_SSL_VERIFYHOST, 2);
        curl_setopt($ch, CURLOPT_TIMEOUT, 3);
        curl_setopt($ch, CURLOPT_HEADER, false);
        
        $responseBody = curl_exec($ch);
        $httpCode = curl_getinfo($ch, CURLINFO_HTTP_CODE);

        if ($responseBody === false) {
            $responseBody = json_encode([
                "error" => "Request failed"
            ]);
            $httpCode = 500;
        }
        curl_close($ch);

        $response = $response->withStatus($httpCode)->withHeader('Content-type', 'application/json');

        $response->getBody()->write($responseBody);

        return $response;
    }

}
